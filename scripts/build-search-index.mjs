// Compiles wiki/pages/ into the two generated artifacts search needs. Both are
// compiled, never hand-edited (conventions P4). Run after any page change:
// node scripts/build-search-index.mjs
//
//   public/search-index.json — compact metadata listing (slug, title, type, focus,
//     summary, domains, region, confidence). No page bodies.
//   api/_search-corpus.mjs — full page text for GET /api/search (the human /search
//     page and visiting agents both grep this). Vercel functions
//     cannot read wiki/ off disk at request time, so the corpus ships as a bundled
//     module — the same pattern api/locations.ts uses via api/_locations-data.mjs.
//
// Deterministic: pages sorted by slug, one JSON object per line, no timestamps, so a
// rebuild after an unrelated edit produces no spurious diff.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const meta = (raw, key) => (raw.match(new RegExp(`^\\*\\*${key}:\\*\\* (.+)$`, 'm')) || [])[1]?.trim() || ''
const section = (raw, name) => (raw.match(new RegExp(`## ${name}\\s+([\\s\\S]*?)(?=\\n## |$)`)) || [])[1]?.trim() || ''
const clip = (t, n) => { const s = (t || '').replace(/\s+/g, ' ').trim(); return s.length <= n ? s : s.slice(0, n - 1) + '…' }

/** `## Heading` names, tolerating the doubled `## Evidence## Evidence` seen in the corpus. */
export function sectionNames(raw) {
  return [...raw.matchAll(/^##[ \t]+(.+)$/gm)]
    .map((match) => match[1].split('#')[0].trim())
    .filter(Boolean)
}

export function readPages(pagesDirectory) {
  return fs.readdirSync(pagesDirectory).sort()
    .filter((file) => file.endsWith('.md'))
    .map((file) => ({ file, slug: file.replace(/\.md$/, ''), raw: fs.readFileSync(path.join(pagesDirectory, file), 'utf8') }))
}

/** Metadata-only browse index for the human UI. Never carries page bodies. */
export function buildBrowseIndex(pages) {
  return pages.map(({ file, slug, raw }) => {
    // `**Domain:**` is primary-first and comma-separated. `domain` is the display/search
    // string (what the prerendered /search page reads); `domains` is the filter facet.
    const domains = meta(raw, 'Domain').split(',').map((value) => value.trim().toLowerCase().replace(/\s*\(.*\)$/, '')).filter(Boolean)
    return {
      slug,
      title: (raw.match(/^# (.+)$/m) || [, file])[1].trim(),
      type: meta(raw, 'Type'),
      focus: clip(meta(raw, 'Focus'), 160),
      summary: clip(section(raw, 'Summary'), 200),
      domain: domains.join(', '),
      domains,
      region: meta(raw, 'Region'),
      confidence: meta(raw, 'Confidence'),
    }
  })
}

/** Full text + the section vocabulary, for the /api/search grep engine. */
export function buildCorpus(pages) {
  const sectionPages = new Map()
  const entries = pages.map(({ file, slug, raw }) => {
    for (const name of new Set(sectionNames(raw))) sectionPages.set(name, (sectionPages.get(name) || 0) + 1)
    return {
      slug,
      path: `/pages/${file}`,
      title: (raw.match(/^# (.+)$/m) || [, file])[1].trim(),
      type: meta(raw, 'Type'),
      text: raw,
    }
  })
  const sections = [...sectionPages].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]))
    .map(([name, count]) => ({ name, pages: count }))
  return { sections, pages: entries }
}

// One JSON object per line: compact enough for the browser, still line-diffable.
const lines = (items) => items.map((item) => `  ${JSON.stringify(item)}`).join(',\n')

export function renderBrowseIndex(index) {
  return `{\n"note": "Browse/filter index for greatutah.work — page metadata only. Full-text search is GET https://greatutah.work/api/search?q=<phrase>. Raw pages are https://greatutah.work/pages/<slug>.md",\n"count": ${index.length},\n"pages": [\n${lines(index)}\n]\n}\n`
}

export function renderCorpusModule(corpus) {
  return `// Generated by scripts/build-search-index.mjs; do not edit.\n`
    + `// Full page text for GET /api/search. Bundled as a module because Vercel functions\n`
    + `// cannot read wiki/ from disk at request time (same pattern as _locations-data.mjs).\n`
    + `export default {\n"sections": [\n${lines(corpus.sections)}\n],\n"pages": [\n${lines(corpus.pages)}\n]\n}\n`
}

export function run({ pagesDirectory, indexOutputFile, corpusOutputFile, check = false }) {
  const pages = readPages(pagesDirectory)
  const indexContent = renderBrowseIndex(buildBrowseIndex(pages))
  const corpusContent = renderCorpusModule(buildCorpus(pages))
  if (check) {
    const stale = [
      !fs.existsSync(indexOutputFile) || fs.readFileSync(indexOutputFile, 'utf8') !== indexContent ? indexOutputFile : null,
      !fs.existsSync(corpusOutputFile) || fs.readFileSync(corpusOutputFile, 'utf8') !== corpusContent ? corpusOutputFile : null,
    ].filter(Boolean)
    if (stale.length) throw new Error(`search artifacts are STALE (${stale.join(', ')}) - run: node scripts/build-search-index.mjs`)
    console.log('search artifacts are fresh')
    return
  }
  fs.writeFileSync(indexOutputFile, indexContent)
  fs.writeFileSync(corpusOutputFile, corpusContent)
  const kb = (text) => `${Math.round(Buffer.byteLength(text) / 1024)}KB`
  console.log(`search: ${pages.length} pages -> ${indexOutputFile} (${kb(indexContent)}), ${corpusOutputFile} (${kb(corpusContent)})`)
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
  try {
    run({
      pagesDirectory: path.join(root, 'wiki', 'pages'),
      indexOutputFile: path.join(root, 'public', 'search-index.json'),
      corpusOutputFile: path.join(root, 'api', '_search-corpus.mjs'),
      check: process.argv.includes('--check'),
    })
  } catch (error) {
    console.error(error.message)
    process.exitCode = 1
  }
}
